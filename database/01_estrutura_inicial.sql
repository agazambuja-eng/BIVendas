-- ---------------------------------------------------------------------
-- 1. METAS DA LOJA  (já criada pelo Table Editor em 22/10/2026)
--    codigo      = código da loja no ERP Savwin (ex.: 520)
--    descricao   = nome da loja
--    valor_meta  = meta de venda líquida do mês, em R$
--    competencia = AAAAMM  (ex.: 202610 = outubro/2026)
-- ---------------------------------------------------------------------
create table if not exists public.metas_loja (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  codigo       int4    not null,
  descricao    text    not null,
  valor_meta   numeric(14,2) not null,
  competencia  int4    not null
);

-- Regras: competência válida e uma única meta por loja/mês
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'metas_loja_competencia_valida') then
    alter table public.metas_loja
      add constraint metas_loja_competencia_valida
      check (competencia between 200001 and 209912 and competencia % 100 between 1 and 12);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'metas_loja_loja_mes_unico') then
    alter table public.metas_loja
      add constraint metas_loja_loja_mes_unico unique (codigo, competencia);
  end if;
end $$;


-- ---------------------------------------------------------------------
-- 2. SEGURANÇA (Row Level Security)
--    O BI lê com a chave publishable no navegador: só LEITURA.
--    Inclusão/alteração de metas: pelo painel do Supabase (por enquanto).
-- ---------------------------------------------------------------------
alter table public.metas_loja enable row level security;

drop policy if exists "leitura publica" on public.metas_loja;
create policy "leitura publica" on public.metas_loja
  for select using (true);


